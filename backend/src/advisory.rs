//! Farmer advisory through a locally hosted model (Gemma 3n via an Ollama-compatible `/api/chat` endpoint).
//!
//! Offline by design: the backend only talks to `ADVISORY_BASE_URL`, which should be a model server on the same
//! machine or LAN; no external API is ever called. When it is unset the endpoint answers 503 with setup steps.
//! The model is grounded with facts from verified records and told not to invent measurements; its text is
//! returned separately from those facts and is never fed back into rankings.

use crate::auth::Actor;
use crate::error::ApiError;
use crate::ranking;
use crate::state::AppState;
use crate::supply_chain_handlers::{parse_id, OILSEED_CROPS};
use axum::{extract::State, Json};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

pub const SUPPORTED_LANGUAGE_NAMES: [(&str, &str); 6] = [
    ("en", "English"),
    ("hi", "Hindi"),
    ("mr", "Marathi"),
    ("te", "Telugu"),
    ("ta", "Tamil"),
    ("gu", "Gujarati"),
];

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdvisoryRequest {
    pub question: String,
    #[serde(default = "default_lang")]
    pub language: String,
    #[serde(default)]
    pub farmer_id: Option<String>,
    #[serde(default)]
    pub crop: Option<String>,
    #[serde(default)]
    pub region: Option<String>,
}

fn default_lang() -> String {
    "en".into()
}

#[derive(Debug, Serialize)]
pub struct AdvisoryResponse {
    pub answer: String,
    pub language: String,
    pub model: String,
    /// Verified facts given to the model as context. The answer may only rely on these plus general knowledge.
    pub grounded_on: Vec<String>,
    pub guidance_type: &'static str,
    pub disclaimer: &'static str,
    pub generated_at: String,
}

const DISCLAIMER: &str = "General agronomic guidance generated by a local language model. Sowing dates, pest \
    pressure, prices and input doses depend on season, region and current conditions: confirm with your local \
    Krishi Vigyan Kendra or agriculture officer before acting. Figures not listed under `grounded_on` are not \
    measurements.";

/// Facts about the farmer from verified records (no personal data).
async fn grounding(state: &AppState, farmer_id: &str) -> Result<Vec<String>, ApiError> {
    let dataset = ranking::load_dataset(state).await?;
    let Some(f) = dataset.farmers.iter().find(|f| f.farmer_id == farmer_id) else {
        return Err(ApiError::NotFound("farmer not found".into()));
    };
    let mut facts = vec![format!("Verified lots on record: {}.", f.lots.len())];
    if let Some(c) = &f.primary_crop {
        facts.push(format!("Primary crop: {c}."));
    }
    let crops: Vec<_> = f.lots.iter().filter_map(|l| l.crop.clone()).collect();
    if !crops.is_empty() {
        facts.push(format!("Crops sold through the FPO: {}.", crops.join(", ")));
    }
    let inspected: Vec<bool> = f.lots.iter().filter_map(|l| l.inspection_passed).collect();
    if !inspected.is_empty() {
        facts.push(format!(
            "Warehouse inspections: {} of {} lots passed.",
            inspected.iter().filter(|p| **p).count(),
            inspected.len()
        ));
    }
    let on_time: Vec<bool> = f.lots.iter().filter_map(|l| l.on_time).collect();
    if !on_time.is_empty() {
        facts.push(format!(
            "Deliveries on time: {} of {}.",
            on_time.iter().filter(|p| **p).count(),
            on_time.len()
        ));
    }
    Ok(facts)
}

/// POST /api/advisory (participants)
pub async fn advise(
    State(state): State<AppState>,
    actor: Actor,
    Json(req): Json<AdvisoryRequest>,
) -> Result<Json<AdvisoryResponse>, ApiError> {
    if !actor.is_admin {
        actor.require_any_role()?;
    }
    let cfg = &state.config.advisory;
    let Some(base_url) = cfg.base_url.as_deref() else {
        return Err(ApiError::Unavailable(
            "advisory model is not configured: run a local Ollama server (`ollama pull gemma3n:e2b`) and set \
             ADVISORY_BASE_URL=http://127.0.0.1:11434"
                .into(),
        ));
    };
    let lang = req.language.trim().to_lowercase();
    if !cfg.languages.contains(&lang) {
        return Err(ApiError::BadRequest(format!(
            "language `{lang}` is not enabled; enabled: {:?} (ADVISORY_LANGUAGES)",
            cfg.languages
        )));
    }
    let lang_name = SUPPORTED_LANGUAGE_NAMES
        .iter()
        .find(|(c, _)| *c == lang)
        .map(|(_, n)| *n)
        .ok_or_else(|| ApiError::BadRequest(format!("language `{lang}` has no configured name")))?;
    let question = req.question.trim();
    if question.is_empty() || question.chars().count() > 1000 {
        return Err(ApiError::bad_request("question must be 1-1000 characters"));
    }
    let mut facts = Vec::new();
    if let Some(fid) = &req.farmer_id {
        let id = crate::chain::hex32(parse_id("farmer_id", fid)?);
        facts.extend(grounding(&state, &id).await?);
    }
    if let Some(c) = &req.crop {
        let c = c.trim().to_lowercase();
        if !OILSEED_CROPS.contains(&c.as_str()) {
            return Err(ApiError::BadRequest(format!(
                "crop must be one of {OILSEED_CROPS:?}"
            )));
        }
        facts.push(format!("Crop asked about: {c}."));
    }
    if let Some(r) = &req.region {
        let r = r.trim();
        if r.is_empty() || r.len() > 120 {
            return Err(ApiError::bad_request("region must be 1-120 characters"));
        }
        facts.push(format!("Region stated by the user: {r}."));
    }

    let system = format!(
        "You are an agricultural extension assistant for Indian oilseed farmers. Answer in {lang_name}. \
         Use only general, well-established agronomic knowledge plus the FACTS below. Never invent measurements, \
         yields, prices, dates or test results. If the question needs local, current or field-specific data you \
         do not have (weather, prices, soil test, pest outbreak), say so and recommend contacting the local KVK or \
         agriculture officer. Keep the answer under 200 words.\nFACTS:\n{}",
        if facts.is_empty() { "(none)".to_string() } else { facts.join("\n") }
    );
    let body = json!({
        "model": cfg.model,
        "stream": false,
        "options": {"temperature": 0.2},
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": question},
        ]
    });
    let resp = state
        .http
        .post(format!("{base_url}/api/chat"))
        .json(&body)
        .send()
        .await
        .map_err(|e| ApiError::Unavailable(format!("advisory model unreachable: {e}")))?;
    if !resp.status().is_success() {
        let status = resp.status();
        let text = resp.text().await.unwrap_or_default();
        return Err(ApiError::Unavailable(format!(
            "advisory model error {status}: {}",
            text.chars().take(200).collect::<String>()
        )));
    }
    let v: Value = resp
        .json()
        .await
        .map_err(|e| ApiError::Unavailable(format!("advisory model returned invalid JSON: {e}")))?;
    let answer = v["message"]["content"]
        .as_str()
        .map(str::trim)
        .filter(|a| !a.is_empty())
        .ok_or_else(|| ApiError::Unavailable("advisory model returned an empty answer".into()))?;
    Ok(Json(AdvisoryResponse {
        answer: answer.to_string(),
        language: lang,
        model: cfg.model.clone(),
        grounded_on: facts,
        guidance_type: "general",
        disclaimer: DISCLAIMER,
        generated_at: crate::db::now(),
    }))
}

#[derive(Debug, Serialize)]
pub struct AdvisoryStatus {
    pub configured: bool,
    pub reachable: bool,
    pub model: String,
    pub model_available: Option<bool>,
    pub languages: Vec<String>,
    pub detail: Option<String>,
}

/// GET /api/advisory/status
pub async fn status(State(state): State<AppState>) -> Json<AdvisoryStatus> {
    let cfg = &state.config.advisory;
    let mut s = AdvisoryStatus {
        configured: cfg.base_url.is_some(),
        reachable: false,
        model: cfg.model.clone(),
        model_available: None,
        languages: cfg.languages.clone(),
        detail: None,
    };
    let Some(base) = &cfg.base_url else {
        s.detail = Some("ADVISORY_BASE_URL is not set".into());
        return Json(s);
    };
    match state.http.get(format!("{base}/api/tags")).send().await {
        Ok(r) if r.status().is_success() => {
            s.reachable = true;
            if let Ok(v) = r.json::<Value>().await {
                let available = v["models"].as_array().is_some_and(|ms| {
                    ms.iter().any(|m| {
                        m["name"].as_str().is_some_and(|n| {
                            n == cfg.model || n.starts_with(&format!("{}:", cfg.model))
                        })
                    })
                });
                s.model_available = Some(available);
                if !available {
                    s.detail = Some(format!(
                        "model `{}` is not pulled on the advisory server",
                        cfg.model
                    ));
                }
            }
        }
        Ok(r) => s.detail = Some(format!("advisory server answered {}", r.status())),
        Err(e) => s.detail = Some(format!("advisory server unreachable: {e}")),
    }
    Json(s)
}
